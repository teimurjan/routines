// Writes the Swift theme and the CSS of packages/ui from design/tokens.json. See specs/002-plugin-ui/contracts/tokens.md.
import { readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

type Result<T> = { ok: true; value: T } | { ok: false; error: string };

const ok = <T>(value: T): Result<T> => ({ ok: true, value });
const err = (error: string): Result<never> => ({ ok: false, error });

export const WEIGHTS = { regular: 400, medium: 500, semibold: 600, bold: 700 } as const;

type Weight = keyof typeof WEIGHTS;
type Named<T> = [name: string, value: T][];

export type Tokens = {
  color: Named<{ light: string; dark: string }>;
  opacity: Named<number>;
  font: Named<{ size: number; weight: Weight }>;
  space: Named<number>;
  size: Named<number>;
  padding: Named<{ x: number; y: number }>;
  radius: Named<number>;
  shadow: Named<{ opacity: number; radius: number; y: number }>;
};

type Group = keyof Tokens;

const HEADER = "Generated by scripts/build-tokens.ts from design/tokens.json. Do not edit.";
const KEBAB = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;
const NUMBER_NAME = /^\d+$/;
const HEX = /^#([0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$/;

const isRecord = (value: unknown): value is Record<string, unknown> => typeof value === "object" && value !== null && !Array.isArray(value);

const isNumber = (value: unknown): value is number => typeof value === "number" && Number.isFinite(value);

const numbers = <Key extends string>(path: string, value: unknown, keys: Key[]): Result<Record<Key, number>> => {
  if (!isRecord(value)) return err(`${path}: expected an object with ${keys.join(", ")}`);
  const missing = keys.find((key) => !isNumber(value[key]));
  return missing ? err(`${path}.${missing}: expected a number`) : ok(value as Record<Key, number>);
};

const hex = (path: string, value: unknown): Result<string> =>
  typeof value === "string" && HEX.test(value) ? ok(value.toUpperCase()) : err(`${path}: ${JSON.stringify(value)} is not a hex color with 6 or 8 digits`);

const color = (path: string, value: unknown): Result<{ light: string; dark: string }> => {
  if (!isRecord(value)) return err(`${path}: expected { light, dark }`);
  const light = hex(`${path}.light`, value.light);
  if (!light.ok) return light;
  const dark = hex(`${path}.dark`, value.dark);
  return dark.ok ? ok({ light: light.value, dark: dark.value }) : dark;
};

const opacity = (path: string, value: unknown): Result<number> =>
  isNumber(value) && value >= 0 && value <= 1 ? ok(value) : err(`${path}: expected a number from 0 to 1`);

const points = (path: string, value: unknown): Result<number> => (isNumber(value) ? ok(value) : err(`${path}: expected a number`));

const font = (path: string, value: unknown): Result<{ size: number; weight: Weight }> => {
  if (!isRecord(value) || !isNumber(value.size)) return err(`${path}: expected { size, weight }`);
  const { weight } = value;
  if (typeof weight !== "string" || !(weight in WEIGHTS)) return err(`${path}.weight: ${JSON.stringify(weight)} is not one of ${Object.keys(WEIGHTS).join(", ")}`);
  return ok({ size: value.size, weight: weight as Weight });
};

const PARSERS: Record<Group, (path: string, value: unknown) => Result<unknown>> = {
  color,
  opacity,
  font,
  space: points,
  size: points,
  padding: (path, value) => numbers(path, value, ["x", "y"]),
  radius: points,
  shadow: (path, value) => {
    const parsed = numbers(path, value, ["opacity", "radius", "y"]);
    if (!parsed.ok) return parsed;
    const alpha = opacity(`${path}.opacity`, parsed.value.opacity);
    return alpha.ok ? parsed : alpha;
  },
};

const GROUPS = Object.keys(PARSERS) as Group[];

// A space token is named by its number, and every other token by a kebab name.
const validName = (group: Group, name: string) => (group === "space" ? NUMBER_NAME.test(name) : KEBAB.test(name));

const parseGroup = (group: Group, value: unknown): Result<Named<unknown>> => {
  if (!isRecord(value)) return err(`${group}: expected an object`);
  const entries: Named<unknown> = [];
  for (const [name, raw] of Object.entries(value)) {
    if (!validName(group, name)) return err(`${group}.${name}: ${group === "space" ? "a space name is a number" : "a name is kebab case"}`);
    const parsed = PARSERS[group](`${group}.${name}`, raw);
    if (!parsed.ok) return parsed;
    entries.push([name, parsed.value]);
  }
  return ok(entries);
};

export const parseTokens = (source: unknown): Result<Tokens> => {
  if (!isRecord(source)) return err("the token file must hold an object");
  const unknown = Object.keys(source).find((group) => !GROUPS.includes(group as Group));
  if (unknown) return err(`${unknown}: unknown group, expected one of ${GROUPS.join(", ")}`);
  const tokens: Partial<Record<Group, Named<unknown>>> = {};
  for (const group of GROUPS) {
    const parsed = parseGroup(group, source[group] ?? {});
    if (!parsed.ok) return parsed;
    tokens[group] = parsed.value;
  }
  // Each parser above returns the value type of its group.
  return ok(tokens as Tokens);
};

export const swiftName = (group: Group, name: string) => {
  const camel = name.replace(/-([a-z0-9])/g, (_, letter: string) => letter.toUpperCase());
  return group === "space" ? `s${camel}` : camel;
};

// Swift takes 8 hex digits with the alpha last.
const swiftHex = (value: string) => `0x${value.slice(1)}${value.length === 7 ? "FF" : ""}`;

const swiftEnum = <T>(name: string, group: Group, entries: Named<T>, type: string, value: (entry: T) => string) =>
  [`    enum ${name} {`, ...entries.map(([key, entry]) => `        static let ${swiftName(group, key)}${type ? `: ${type}` : ""} = ${value(entry)}`), "    }"];

export const swiftOutput = (tokens: Tokens) =>
  [
    `// ${HEADER}`,
    "import SwiftUI",
    "",
    "enum Tokens {",
    "    struct Inset { let x: CGFloat; let y: CGFloat }",
    "    struct ShadowStyle { let opacity: Double; let radius: CGFloat; let y: CGFloat }",
    "",
    ...swiftEnum("Color", "color", tokens.color, "", ({ light, dark }) => `SwiftUI.Color(light: ${swiftHex(light)}, dark: ${swiftHex(dark)})`),
    ...swiftEnum("Opacity", "opacity", tokens.opacity, "Double", String),
    ...swiftEnum("Font", "font", tokens.font, "", ({ size, weight }) => `SwiftUI.Font.system(size: ${size}, weight: .${weight})`),
    ...swiftEnum("Space", "space", tokens.space, "CGFloat", String),
    ...swiftEnum("Size", "size", tokens.size, "CGFloat", String),
    ...swiftEnum("Padding", "padding", tokens.padding, "", ({ x, y }) => `Inset(x: ${x}, y: ${y})`),
    ...swiftEnum("Radius", "radius", tokens.radius, "CGFloat", String),
    ...swiftEnum("Shadow", "shadow", tokens.shadow, "", ({ opacity, radius, y }) => `ShadowStyle(opacity: ${opacity}, radius: ${radius}, y: ${y})`),
    "}",
    "",
  ].join("\n");

const cssShadow = ({ opacity, radius, y }: { opacity: number; radius: number; y: number }) => `0 ${y}px ${radius}px rgb(0 0 0 / ${opacity})`;

export const cssOutput = (tokens: Tokens) => {
  const line = (name: string, value: string | number) => `  --${name}: ${value};`;
  return [
    `/* ${HEADER} */`,
    ":root {",
    ...tokens.color.map(([name, { light }]) => line(name, light)),
    ...tokens.opacity.map(([name, value]) => line(`opacity-${name}`, value)),
    ...tokens.font.flatMap(([name, { size, weight }]) => [line(`font-${name}-size`, `${size}px`), line(`font-${name}-weight`, WEIGHTS[weight])]),
    ...tokens.space.map(([name, value]) => line(`space-${name}`, `${value}px`)),
    ...tokens.size.map(([name, value]) => line(`size-${name}`, `${value}px`)),
    ...tokens.padding.map(([name, { x, y }]) => line(`padding-${name}`, `${y}px ${x}px`)),
    ...tokens.radius.map(([name, value]) => line(`radius-${name}`, `${value}px`)),
    ...tokens.shadow.map(([name, value]) => line(`shadow-${name}`, cssShadow(value))),
    "}",
    "@media (prefers-color-scheme: dark) {",
    "  :root {",
    ...tokens.color.map(([name, { dark }]) => `  ${line(name, dark)}`),
    "  }",
    "}",
    "",
  ].join("\n");
};

const ROOT = join(import.meta.dir, "..");
const SOURCE = join(ROOT, "design/tokens.json");
const OUTPUTS = [
  { path: join(ROOT, "app/Sources/Routines/Views/Tokens.swift"), render: swiftOutput },
  { path: join(ROOT, "packages/ui/src/tokens.css"), render: cssOutput },
];

const readOrEmpty = (path: string) => {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return "";
  }
};

const readSource = (): unknown => {
  try {
    return JSON.parse(readFileSync(SOURCE, "utf8"));
  } catch (cause) {
    return `invalid JSON: ${(cause as Error).message}`;
  }
};

const main = (check: boolean) => {
  const tokens = parseTokens(readSource());
  if (!tokens.ok) {
    console.error(`design/tokens.json: ${tokens.error}`);
    return 1;
  }
  const stale = OUTPUTS.filter(({ path, render }) => readOrEmpty(path) !== render(tokens.value));
  if (check) {
    for (const { path } of stale) console.error(`${relative(ROOT, path)} differs from design/tokens.json. Run bun run tokens.`);
    return stale.length > 0 ? 1 : 0;
  }
  for (const { path, render } of stale) writeFileSync(path, render(tokens.value));
  console.log(`tokens: ${stale.length} of ${OUTPUTS.length} files written`);
  return 0;
};

if (import.meta.main) process.exit(main(process.argv.includes("--check")));
